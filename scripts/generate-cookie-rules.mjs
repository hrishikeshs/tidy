import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";

const inputPath = resolve(process.argv[2] ?? "/tmp/tidy-open-cookie-database.json");
const outputPath = resolve(
  process.argv[3] ?? "web-extension/shared/open-cookie-rules.generated.js"
);

const CATEGORY_CODES = Object.freeze({
  Analytics: "a",
  Functional: "f",
  Marketing: "m",
  Necessary: "f",
  Personalization: "p",
  Security: "s"
});

function normalizedText(value, maximumLength = 240) {
  return String(value ?? "").replace(/\s+/g, " ").trim().slice(0, maximumLength);
}

function domainsFrom(rawDomain) {
  const domains = [];
  const pattern = /(?:https?:\/\/)?(?:www\.)?([a-z0-9](?:[a-z0-9-]*[a-z0-9])?(?:\.[a-z0-9](?:[a-z0-9-]*[a-z0-9])?)+)/gi;
  for (const match of String(rawDomain ?? "").matchAll(pattern)) {
    const domain = match[1].toLowerCase();
    if (!domains.includes(domain)) domains.push(domain);
  }
  return domains.sort();
}

const sourceText = await readFile(inputPath, "utf8");
const source = JSON.parse(sourceText);
const rules = Object.values(source)
  .flat()
  .map((record) => ({
    name: normalizedText(record.cookie, 160),
    category: CATEGORY_CODES[record.category],
    wildcard: record.wildcardMatch === "1",
    domains: domainsFrom(record.domain),
    description: normalizedText(record.description),
    controller: normalizedText(record.dataController, 120)
  }))
  .filter(({ name, category }) => name && category)
  .filter(({ name, domains }) => name.length >= 3 || domains.length > 0);

const uniqueRules = [...new Map(
  rules.map((rule) => [JSON.stringify(rule), rule])
).values()].sort((left, right) =>
  left.name.localeCompare(right.name)
  || Number(left.wildcard) - Number(right.wildcard)
  || left.category.localeCompare(right.category)
  || left.domains.join(",").localeCompare(right.domains.join(","))
);

const checksum = createHash("sha256").update(sourceText).digest("hex");
const compactRules = uniqueRules.map(({ name, category, wildcard, domains, description, controller }) =>
  [name, category, wildcard ? 1 : 0, domains, description, controller]
);
const output = `// Generated by scripts/generate-cookie-rules.mjs; do not edit by hand.\n`
  + `// Source: Open Cookie Database (Apache-2.0).\n`
  + `export const OPEN_COOKIE_DATABASE_META = Object.freeze(${JSON.stringify({
    source: "Open Cookie Database",
    sourceURL: "https://github.com/jkwakman/Open-Cookie-Database",
    license: "Apache-2.0",
    sha256: checksum,
    ruleCount: compactRules.length
  })});\n\n`
  + `export const OPEN_COOKIE_RULES = Object.freeze(${JSON.stringify(compactRules)});\n`;

await writeFile(outputPath, output);
process.stdout.write(`Generated ${compactRules.length} cookie rules at ${outputPath}.\n`);
